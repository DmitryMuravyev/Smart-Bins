"""Bundles the web UI (web/) into the firmware as gzipped byte arrays.

Runs as a PlatformIO pre-build script (extra_scripts = pre:tools/embed_web.py)
and can also be run by hand: python tools/embed_web.py

Why embedded instead of files on the data partition: one firmware image (also over the
air) always carries the matching UI, there is no separate "upload filesystem"
step, and the data partition stays free for the inventory and photos.

The script also checks that every translation file has exactly the keys of
en.json, so a missing string fails the build instead of showing up as a raw
key in the UI.
"""

import gzip
import hashlib
import json
import os
import sys

MIME = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
}


def project_dir():
    try:
        Import("env")  # noqa: F821  (defined by PlatformIO/SCons)
        return env["PROJECT_DIR"]  # noqa: F821
    except NameError:
        return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def check_translations(web_dir):
    i18n = os.path.join(web_dir, "i18n")
    with open(os.path.join(i18n, "en.json"), encoding="utf-8") as f:
        reference = set(json.load(f))
    problems = []
    for name in sorted(os.listdir(i18n)):
        if not name.endswith(".json") or name == "en.json":
            continue
        with open(os.path.join(i18n, name), encoding="utf-8") as f:
            keys = set(json.load(f))
        for k in sorted(reference - keys):
            problems.append(f"{name}: missing {k}")
        for k in sorted(keys - reference):
            problems.append(f"{name}: unknown key {k} (not in en.json)")
    return problems


def collect(web_dir):
    files = []
    for root, _, names in os.walk(web_dir):
        for name in sorted(names):
            ext = os.path.splitext(name)[1].lower()
            if ext not in MIME:
                continue
            path = os.path.join(root, name)
            url = "/" + os.path.relpath(path, web_dir).replace(os.sep, "/")
            files.append((url, path, MIME[ext]))
    return sorted(files)


def render(files):
    lines = [
        "// Generated by tools/embed_web.py from the files in web/. Do not edit.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace sb {",
        "namespace web {",
        "",
        "struct WebAsset {",
        "  const char *path;",
        "  const char *mime;",
        "  const char *etag;  // content hash, for If-None-Match",
        "  const uint8_t *gz;",
        "  size_t size;",
        "};",
        "",
    ]
    entries = []
    for i, (url, path, mime) in enumerate(files):
        with open(path, "rb") as f:
            raw = f.read()
        # mtime=0 keeps the output identical for identical input, so the
        # header (and the firmware) only change when a web file changes.
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        etag = '"' + hashlib.sha1(raw).hexdigest()[:16] + '"'
        body = ",".join(str(b) for b in gz)
        lines.append(f"// {url}: {len(raw)} bytes, {len(gz)} gzipped")
        lines.append(f"const uint8_t kAsset{i}[] = {{{body}}};")
        entries.append(f'    {{"{url}", "{mime}", "{etag.replace(chr(34), chr(92) + chr(34))}", kAsset{i}, sizeof(kAsset{i})}},')
    lines.append("")
    lines.append("const WebAsset kWebAssets[] = {")
    lines.extend(entries)
    lines.append("};")
    lines.append("constexpr size_t kWebAssetCount = sizeof(kWebAssets) / sizeof(kWebAssets[0]);")
    lines.append("")
    lines.append("}  // namespace web")
    lines.append("}  // namespace sb")
    return "\n".join(lines) + "\n"


def main():
    root = project_dir()
    web_dir = os.path.join(root, "web")
    problems = check_translations(web_dir)
    if problems:
        for p in problems:
            print(f"embed_web: {p}", file=sys.stderr)
        sys.exit("embed_web: translation files do not match en.json")

    files = collect(web_dir)
    out_path = os.path.join(root, "src", "generated", "WebAssets.h")
    text = render(files)
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    old = None
    if os.path.exists(out_path):
        with open(out_path, encoding="utf-8") as f:
            old = f.read()
    # Rewrite only on change, so an unchanged UI doesn't trigger a rebuild.
    if old != text:
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(text)
    total = sum(os.path.getsize(p) for _, p, _ in files)
    print(f"embed_web: {len(files)} files, {total} bytes -> {os.path.relpath(out_path, root)}")


main()
